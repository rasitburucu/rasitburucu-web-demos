/** Turkish 3rd-person possessive suffix after a numeral: 5'i, 2'si, 3'ü, 6'sı ... */
export function possessive(n: number) {
  const table: Record<number, string> = {
    0: "'ı", 1: "'i", 2: "'si", 3: "'ü", 4: "'ü", 5: "'i", 6: "'sı", 7: "'si", 8: "'i", 9: "'u", 10: "'u", 11: "'i", 12: "'si",
  };
  return `${n}${table[n] ?? "'i"}`;
}

/** Turkish accusative suffix after a villa numeral: 07'yi, 01'i, 03'ü ... */
export function accusative(no: string) {
  const n = parseInt(no, 10);
  const table: Record<number, string> = {
    1: "'i", 2: "'yi", 3: "'ü", 4: "'ü", 5: "'i", 6: "'yı", 7: "'yi", 8: "'i", 9: "'u", 10: "'u", 11: "'i", 12: "'yi",
  };
  return `${no}${table[n] ?? "'i"}`;
}

